/** Pull the "Our Story" timeline (<p>YEAR</p><p>Title</p><p>…</p>) out of the crawled page. */
function timeline(html) {
  const start = html.indexOf('Our Story');
  if (start < 0) return [];
  const chunk = html.slice(start, html.indexOf('Meet the leadership team') > start ? html.indexOf('Meet the leadership team') : undefined);
  const re = /<p>\s*(20\d\d)\s*<\/p>\s*<p>([^<]+)<\/p>/g;
  const hits = [...chunk.matchAll(re)];
  return hits.map((m, i) => {
    const from = m.index + m[0].length;
    const to = i + 1 < hits.length ? hits[i + 1].index : chunk.search(/<h2>/) > from ? chunk.search(/<h2>/) : chunk.length;
    let body = chunk.slice(from, to).replace(/<h2>[\s\S]*$/, '').trim();
    return { year: m[1], title: m[2].trim(), body };
  });
}

