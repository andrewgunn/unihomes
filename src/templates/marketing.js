const steps = (items, cls = '') =>
  `<ol class="steps ${cls}">${items.map(([t, d]) => `<li><h3>${esc(t)}</h3><p>${esc(d)}</p></li>`).join('')}</ol>`;

const faq = (items) =>
  `<div class="faq">${items.map(([q, a]) => `<details><summary>${esc(q)}${icon('chevronDown')}</summary><div class="faq-a"><p>${esc(a)}</p></div></details>`).join('')}</div>`;

const quotes = (items) =>
  `<div class="reviews mk-quotes">${items
    .map(([q, who, meta]) => `<figure class="review mk-quote"><blockquote><p>“${esc(q)}”</p></blockquote><figcaption><strong>${esc(who)}</strong>${meta ? `<span>${esc(meta)}</span>` : ''}</figcaption></figure>`)
    .join('')}</div>`;

